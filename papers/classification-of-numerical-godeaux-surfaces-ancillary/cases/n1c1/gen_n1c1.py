# Generator for case n1c1 (normal form N1(D), c = 1).  Light Python only: it writes Singular code
# and the table of unknowns; all computation happens in Singular through tools/run_cas.py.
# Notation of plan/case_common.md: coordinates w (deg 1, sigma -), y1 (deg 2, +), y2, y3 (deg 2, -);
# y0 = w^2; generators v0..v5 of degrees c = (0,3,3,3,3,4), sigma-signs (+,-,-,+,+,-).
import os
HERE = os.path.dirname(os.path.abspath(__file__))
c = [0, 3, 3, 3, 3, 4]
dl = [1, -1, -1, 1, 1, -1]
r = [8 - x for x in c]

def mons(n, s):
    """monomials (a,b,e,f) = w^a y1^b y2^e y3^f of weight n = a + 2(b+e+f) and sigma-sign (-1)^(a+e+f) = s"""
    out = []
    for a in range(n + 1):
        if (n - a) % 2:
            continue
        m = (n - a) // 2
        for b in range(m, -1, -1):
            for e in range(m - b, -1, -1):
                f = m - b - e
                if (-1) ** (a + e + f) == s:
                    out.append((a, b, e, f))
    return out

def mstr(ex):
    a, b, e, f = ex
    parts = []
    for v, p in (('w', a), ('y1', b), ('y2', e), ('y3', f)):
        if p == 1:
            parts.append(v)
        elif p > 1:
            parts.append('%s^%d' % (v, p))
    return '*'.join(parts) if parts else '1'

pairs = [(i, j) for i in range(1, 6) for j in range(i, 6)]
# lambda coefficients l(n): (i, j, k, monomial, w-order)
lam = []
lampoly = {}
for (i, j) in pairs:
    for k in range(6):
        ms = mons(c[i] + c[j] - c[k], dl[i] * dl[j] * dl[k])
        terms = []
        for ex in ms:
            lam.append((i, j, k, ex))
            terms.append('l(%d)*%s' % (len(lam), mstr(ex)))
        lampoly[(i, j, k)] = ' + '.join(terms) if terms else '0'
assert len(lam) == 371, len(lam)

# A-unknowns
Gmons = ['y3^3', 'y1^2*y3', 'y2*y3^2', 'y1^2*y2', 'y2^2*y3', 'y2^3', 'y0*y1*y3', 'y0*y1*y2', 'y0^2*y3', 'y0^2*y2']
Gord = [2, 2, 2, 2, 2, 2, 4, 4, 6, 6]
bmons = [('q1', 'y1*y2'), ('q1', 'y1*y3'), ('q2', 'y0*y2'), ('q2', 'y0*y3'), ('q2', 'y1*y2'), ('q2', 'y1*y3'),
         ('q3', 'y0^2'), ('q3', 'y0*y1'), ('q3', 'y1^2'), ('q4', 'y0^2'), ('q4', 'y2*y3'), ('q4', 'y3^2')]
bord = [1 + 2 * m.count('y0') + (2 if 'y0^2' in m else 0) for (_, m) in bmons]
# y0^2 contains 'y0' once in the string but means y0-degree 2: fix explicitly
def y0deg(m):
    if 'y0^2' in m:
        return 2
    return 1 if 'y0' in m else 0
bord = [1 + 2 * y0deg(m) for (_, m) in bmons]
assert bord == [1, 1, 3, 3, 1, 1, 5, 3, 1, 5, 1, 1], bord
assert Gord == [2 + 2 * y0deg(m) for m in Gmons]

NV = 371 + 10 + 12 + 1
ORD = [ex[0] for (_, _, _, ex) in lam] + Gord + bord + [0]
TYP = [1] * 371 + [2] * 10 + [3] * 12 + [4]
assert len(ORD) == NV and len(TYP) == NV

def ivec(name, xs):
    return 'intvec %s = %s;' % (name, ','.join(str(x) for x in xs))

# ---------------- common include (ring R0 with w,y; matrix A; lambda polys) ----------------
C = []
C.append('// common definitions for case n1c1 (generated by gen_n1c1.py)')
C.append('ring R0 = 0, (l(1..371), g(1..10), b(1..12), D, w, y1, y2, y3), dp;')
C.append('short = 0;')
C.append('poly y0 = w^2;')
C.append('poly G = ' + ' + '.join('g(%d)*%s' % (n + 1, m) for n, m in enumerate(Gmons)) + ';')
for qi in ('q1', 'q2', 'q3', 'q4'):
    C.append('poly %s = ' % qi + ' + '.join('b(%d)*%s' % (n + 1, m) for n, (q, m) in enumerate(bmons) if q == qi) + ';')
C.append('poly Q = y2^2 - D*y3^2 - y1^2;')
C.append('int cc = 1;   // the constant c of the normal form')
C.append('matrix A[6][6] = y0*G, w*q1, w*q2, w*q3, w*q4, Q,')
C.append('                 w*q1, D*y3, y2, y1, 0, w,')
C.append('                 w*q2, y2, y3, cc*y0, y1, 0,')
C.append('                 w*q3, y1, cc*y0, -y3, y2, 0,')
C.append('                 w*q4, 0, y1, y2, -D*y3, 0,')
C.append('                 Q, w, 0, 0, 0, 0;')
C.append('proc cofac(matrix M, int rr, int cl) { matrix S5[5][5]; int a, bb, p, q; a = 0; for (p=1; p<=6; p++) { if (p != rr) { a++; bb = 0; for (q=1; q<=6; q++) { if (q != cl) { bb++; S5[a,bb] = M[p,q]; } } } } return((-1)^(rr+cl) * det(S5)); }')
for (i, j) in pairs:
    for k in range(6):
        C.append('poly lam_%d_%d_%d = %s;' % (i, j, k, lampoly[(i, j, k)]))
C.append('< "meta_n1c1.sing";')
open(os.path.join(HERE, 'common_n1c1.sing'), 'w').write('\n'.join(C) + '\n')

# ---------------- metadata include usable in any ring ----------------
LK = [k for (_, _, k, _) in lam] + [-1] * 23
M = [ivec('ORD', ORD), ivec('TYP', TYP), ivec('LK', LK)]
open(os.path.join(HERE, 'meta_n1c1.sing'), 'w').write('\n'.join(M) + '\n')

# ---------------- table of unknowns ----------------
T = ['# unknowns of case n1c1: name | type | monomial (in its entry) | w-order',
     '# lambda l(n) is the coefficient of the monomial in lambda_{ij,k} (1 <= i <= j <= 5, 0 <= k <= 5)',
     '# counts: lambda 371, g 10, b 12, D 1; total 394']
for n, (i, j, k, ex) in enumerate(lam):
    T.append('l(%d) | lambda_{%d%d,%d} | %s | %d' % (n + 1, i, j, k, mstr(ex), ex[0]))
for n, m in enumerate(Gmons):
    T.append('g(%d) | G (entry A00 = y0*G) | %s | %d' % (n + 1, m, Gord[n]))
for n, (q, m) in enumerate(bmons):
    T.append('b(%d) | %s (entry w*%s) | %s | %d' % (n + 1, q, q, m, bord[n]))
T.append('D | parameter of the net | (D*y3 at A11, -D*y3 at A44, -D*y3^2 in Q) | 0')
from collections import Counter
cnt = Counter(ORD)
T.append('# unknowns by w-order: ' + str(dict(sorted(cnt.items()))))
lk = Counter(k for (_, _, k, _) in lam)
T.append('# lambda by k: ' + str(dict(sorted(lk.items()))))
lo = Counter(ex[0] for (_, _, _, ex) in lam)
T.append('# lambda by w-order: ' + str(dict(sorted(lo.items()))))
for o in range(9):
    byk = Counter(k for (_, _, k, ex) in lam if ex[0] == o)
    T.append('#   lambda of w-order %d by k: %s' % (o, dict(sorted(byk.items()))))
open(os.path.join(HERE, 'unknowns_n1c1.txt'), 'w').write('\n'.join(T) + '\n')

# slots per (i,j) and per w-order
slots = Counter()
slot_ij = {}
for (i, j) in pairs:
    ms = mons(8 + c[i] + c[j], -dl[i] * dl[j])
    slot_ij[(i, j)] = len(ms)
    for ex in ms:
        slots[ex[0]] += 1
assert sum(slots.values()) == 920

# ---------------- script A: equations ----------------
L = []
L.append('// n1c1, script A: rank-condition equations, counts per w-order, delay and linearity checks')
L.append('system("--ticks-per-sec", 1000); int T0 = rtimer;')
L.append('< "common_n1c1.sing";')
L.append('int i, j, k, u, m, n, ok;')
L.append('intvec WW = 0:394; WW = WW, 1, 0, 0, 0;          // weight 1 on w only')
L.append('intvec WORD = ORD, 0, 0, 0, 0;                     // w-orders of the unknowns')
L.append('matrix B0[1][6]; for (k=1;k<=6;k++){ B0[1,k] = cofac(A,k,1); }   // B0[1,k] = B_{0,k-1}')
L.append('"cofactors of row 0 built, ms:", rtimer-T0;')
# delay checks
L.append('// ---- delay checks (case_common.md section 2) ----')
L.append('matrix al[4][4]; for (i=1;i<=4;i++){ for (j=1;j<=4;j++){ al[i,j] = subst(A[i+1,j+1], w, 0); } }')
L.append('poly da = det(al); "det(alpha) - Q^2 =", da - Q^2;')
L.append('proc cof4(matrix M, int rr, int cl) { matrix S3[3][3]; int a, bb, p, q; a = 0; for (p=1; p<=4; p++) { if (p != rr) { a++; bb = 0; for (q=1; q<=4; q++) { if (q != cl) { bb++; S3[a,bb] = M[p,q]; } } } } return((-1)^(rr+cl) * det(S3)); }')
L.append('"B_05 mod w + Q^3 =", subst(B0[1,6], w, 0) + Q^3, "   (0 means B_05 = -Q^3 mod w)";')
L.append('for (k=1;k<=4;k++){ poly t0 = subst(B0[1,k+1], w, 0); poly t1 = subst(diff(B0[1,k+1], w), w, 0); "k =", k, ": B_0k mod w =", t0, " ; [w^1]B_0k - Q*adj(alpha)_{k1} =", t1 - Q*cof4(al,1,k); kill t0, t1; }')
L.append('matrix aa[4][4]; for (i=1;i<=4;i++){ for (j=1;j<=4;j++){ aa[i,j] = A[i+1,j+1]; } }')
L.append('"B_00 + y0*adj(a)_{11} =", B0[1,1] + y0*cof4(aa,1,1), "   (a = full 4x4 block incl. y0-terms)";')
# equations
L.append('// ---- equations E_ij = B_ij - sum_k lambda_{ij,k} B_0k, 1 <= i <= j <= 5 ----')
L.append('ideal EQA; intvec EOA; list ETG; poly pol; matrix CM; n = 0;')
L.append('intvec nzij;')
for p, (i, j) in enumerate(pairs):
    terms = ' + '.join('(lam_%d_%d_%d)*B0[1,%d]' % (i, j, k, k + 1) for k in range(6))
    L.append('pol = cofac(A,%d,%d) - (%s);' % (j + 1, i + 1, terms))
    L.append('CM = coef(pol, w*y1*y2*y3); nzij[%d] = ncols(CM); for (u=1;u<=ncols(CM);u++){ n++; EQA[n] = CM[2,u]; EOA[n] = deg(CM[1,u], WW); ETG[n] = list(%d,%d,string(CM[1,u])); }' % (p + 1, i, j))
L.append('"equations built, ms:", rtimer-T0;')
L.append('intvec SLOTIJ = %s;' % ','.join(str(slot_ij[pq]) for pq in pairs))
L.append('intvec SLOTO = %s;' % ','.join(str(slots[o]) for o in range(16)))
L.append('"nonzero coefficient monomials per (i,j) vs slots:"; for (u=1;u<=15;u++){ "  pair", u, ":", nzij[u], "of", SLOTIJ[u]; }')
L.append('// sanity: every extracted coefficient has the weight/sign of a slot (checked by counting: nonzero <= slots)')
L.append('"total nonzero coefficient equations:", n;')
L.append('// per w-order counts and dedup up to scalar')
L.append('ideal EQ; intvec EO; int ne = 0; intvec NZO = 0:16; intvec DSO = 0:16;')
L.append('for (m=0;m<=15;m++){ ideal Im; int cm = 0; for (u=1;u<=n;u++){ if (EOA[u]==m) { cm++; Im[cm] = EQA[u]; } } NZO[m+1] = cm;')
L.append('  ideal Id = simplify(Im, 2+4+8);')
L.append('  int dd = 0; for (u=1;u<=ncols(Id);u++){ if (Id[u] != 0) { dd++; ne++; EQ[ne] = Id[u]; EO[ne] = m; } } DSO[m+1] = dd; kill Im, Id, cm, dd; }')
L.append('"w-order | slots | nonzero coefficient equations | distinct up to scalar";')
L.append('for (m=0;m<=15;m++){ "  ", m, "|", SLOTO[m+1], "|", NZO[m+1], "|", DSO[m+1]; }')
L.append('int s1 = 0; int s2 = 0; int s3 = 0; for (m=1;m<=16;m++){ s1 = s1 + SLOTO[m]; s2 = s2 + NZO[m]; s3 = s3 + DSO[m]; } "totals:", s1, s2, s3;')
L.append('ideal EQg = simplify(EQ, 2+4+8); "distinct up to scalar across all orders:", ncols(EQg);')
L.append('// structure checks: an order-m equation has total unknown-order <= m; for m >= 1 it is linear in the')
L.append('// order-m unknowns, whose coefficients involve only order-0 unknowns')
L.append('int bad1 = 0; int bad2 = 0; int bad3 = 0;')
L.append('for (u=1;u<=ne;u++){ if (deg(EQ[u], WORD) > EO[u]) { bad1++; } }')
L.append('intvec Wp = 0:398; for (k=1;k<=394;k++){ if (ORD[k]>=1) { Wp[k] = 1; } }')
L.append('for (m=1;m<=15;m++){ intvec Wm = 0:398; ideal zm; for (k=1;k<=398;k++){ zm[k] = var(k); } for (k=1;k<=394;k++){ if (ORD[k]==m) { Wm[k] = 1; zm[k] = 0; } } map ph = R0, zm;')
L.append('  for (u=1;u<=ne;u++){ if (EO[u]==m) { poly f0 = EQ[u]; poly f1 = f0 - ph(f0); if (f1 != 0) { if (deg(f1, Wm) > 1) { bad2++; } if (deg(f1, Wp) > 1) { bad3++; } } kill f0, f1; } } kill Wm, zm, ph; }')
L.append('"equations with a term of total unknown-order > m:", bad1;')
L.append('"equations (m>=1) nonlinear in order-m unknowns:", bad2, " ; with order-m coefficients involving unknowns of order >= 1:", bad3;')
L.append('// write the distinct equations (with their w-orders) for the elimination script')
L.append('write(":w eqs_n1c1.txt", "// distinct coefficient equations of case n1c1 (written by n1c1_A_eqs.sing)");')
L.append('for (u=1;u<=ne;u++){ write(":a eqs_n1c1.txt", "EQ[" + string(u) + "]=" + string(EQ[u]) + "; EO[" + string(u) + "]=" + string(EO[u]) + ";"); }')
L.append('"wrote eqs_n1c1.txt with", ne, "equations; ms:", rtimer-T0, " memory KB:", memory(2) div 1024;')
L.append('quit;')
open(os.path.join(HERE, 'n1c1_A_eqs.sing'), 'w').write('\n'.join(L) + '\n')
print('generated: common_n1c1.sing, meta_n1c1.sing, unknowns_n1c1.txt, n1c1_A_eqs.sing; slots by order', dict(sorted(slots.items())))
