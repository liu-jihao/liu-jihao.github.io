#!/usr/bin/env python3
"""Case n3: light generator (no CAS) for n3_aux.sing:
 (i) w-adic leading terms of the row-0 cofactors B_0k (precise delays for N3);
 (ii) exact torus homogeneity: every nonzero coefficient equation is homogeneous for the T1-weights of the 393 unknowns,
      and every eliminated g, b expression of n3_final.sing is homogeneous of the weight of that unknown."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, 'gen_n3_checks.py')).read()
exec(src.split("L = []\nL.append('// n3_checks.sing")[0])
T1 = [1, 0, 0, -2, 2, 1, -1, -1, 1, -2]
WT1 = [sum(a * b for a, b in zip(v, T1)) for v in WC]
K = -min(WT1)
L = []
L.append('// n3_aux.sing (generated by gen_n3_aux.py)')
L.append('system("--ticks-per-sec", 1000); int T0 = rtimer;')
L.append('< "n3_build.sing";')
L.append('"(i) w-adic order and leading coefficient of the row-0 cofactors B_0k (k = 0..5):";')
L.append('int d; poly hd; int fac;')
L.append('for (k=1;k<=6;k++) { d = 0; hd = B0[1,k]; fac = 1; while (subst(hd, w, 0) == 0 && d < 20) { hd = diff(hd, w); d++; fac = fac*d; } "  B_0" + string(k-1) + ": w-order " + string(d) + ", coefficient of w^" + string(d) + " = " + string(subst(hd, w, 0)/fac); }')
L.append('ideal EQI; for (u=1;u<=nEQ;u++){ EQI[u] = EQ[u]; }')
L.append('ring S = 0, (lam(1..371), g(1..10), b(1..12)), dp;')
L.append('ideal EQI = imap(R, EQI);')
L.append('ideal FIN = maxideal(1);')
L.append('< "n3_final.sing";')
L.append('ring S2 = 0, (lam(1..371), g(1..10), b(1..12), s, z), dp;')
L.append('ideal EQI = imap(S, EQI); ideal FIN = imap(S, FIN);')
L.append('intvec WT1 = %s;' % ','.join(str(x) for x in WT1))
L.append('int K = %d;' % K)
L.append('ideal IM = maxideal(1); for (u=1;u<=393;u++){ IM[u] = s^(WT1[u]+K)*z*var(u); }')
L.append('map PH = S2, IM;')
L.append('proc wset(poly f, int K)')
L.append('{')
L.append('  // weights (s-exponent - K*z-exponent) of the terms of f, returned as intvec of distinct values')
L.append('  intvec ws; int nw = 0; int ii, jj, wt, fnd; intvec ex;')
L.append('  for (ii=1; ii<=size(f); ii++) { ex = leadexp(f[ii]); wt = ex[394] - K*ex[395]; fnd = 0; for (jj=1;jj<=nw;jj++){ if (ws[jj] == wt) { fnd = 1; } } if (fnd == 0) { nw++; ws[nw] = wt; } }')
L.append('  return(ws);')
L.append('}')
L.append('int nnh = 0; poly im; intvec wv; int ne = ncols(EQI);')
L.append('for (u=1;u<=ne;u++){ im = EQI[u]; im = PH(im); wv = wset(im, K); if (size(wv) > 1) { nnh++; } }')
L.append('"(ii) nonzero coefficient equations:", ne, "; not homogeneous for the T1-weights:", nnh;')
L.append('int nng = 0; for (u=372;u<=393;u++){ im = FIN[u]; if (im != var(u) && im != 0) { im = PH(im); wv = wset(im, K); if (size(wv) > 1 || wv[1] != WT1[u]) { nng++; "   not equivariant:", var(u); } } }')
L.append('"(ii) eliminated g, b whose expression is not homogeneous of the weight of the unknown (zero expressions skipped):", nng;')
L.append('int nnl = 0; for (u=1;u<=371;u++){ im = FIN[u]; if (im != var(u) && im != 0) { im = PH(im); wv = wset(im, K); if (size(wv) > 1 || wv[1] != WT1[u]) { nnl++; } } }')
L.append('"(ii) eliminated lambda whose expression is not homogeneous of the weight of the unknown (zero expressions skipped):", nnl;')
L.append('"== done; ms:", rtimer - T0, "; memory (KB):", memory(1) div 1024, "; max:", memory(2) div 1024;')
L.append('quit;')
open(os.path.join(HERE, 'n3_aux.sing'), 'w').write('\n'.join(L) + '\n')
print('written n3_aux.sing; K =', K, '; T1-weights of g,b:', WT1[371:])
