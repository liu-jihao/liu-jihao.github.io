# Generator of the mod-p tangent check (case_common.md section 6) for case n2 (evidence only).
import os, sys, random
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_n2 import RING, write

def modp_script(cval, mode, seeds, p=32003):
    L = []
    L.append('// n2, c = %d: mod-%d tangent check at random points of the solution scheme (state n2c%d_%s_state.ssi); generated by gen_n2_modp.py' % (cval, p, cval, mode))
    L.append('system("--ticks-per-sec", 1000); int T0 = rtimer; LIB "matrix.lib";')
    L.append(RING)
    L.append('< "n2_defs.sing";')
    L.append('link LE = "ssi:r n2c%d_eqs.ssi"; def S = read(LE); close(LE); list EQS = S[1]; kill S;' % cval)
    L.append('link LS = "ssi:r n2c%d_%s_state.ssi"; def ST = read(LS); close(LS); ideal IMG = ST[1]; intvec ELIMAT = ST[2]; ideal LEFT = ST[4]; kill ST;' % (cval, mode))
    L.append('"equations:", size(EQS), "; leftover equations in the state:", size(simplify(LEFT,2));')
    L.append('ring RP = %d, (l(1..371), g(1..10), b(1..12), w, y1, y2, y3), dp;' % p)
    L.append('list EQS = fetch(R, EQS); ideal IMG = fetch(R, IMG); int u; int v;')
    L.append('ideal EI; for (u = 1; u <= size(EQS); u++) { EI[u] = EQS[u]; }')
    L.append('matrix J = jacob(EI); "Jacobian:", nrows(J), "x", ncols(J), "; ms:", rtimer-T0;')
    L.append('int nfree = 0; int nfA = 0; for (v = 1; v <= 393; v++) { if (ELIMAT[v] == 0) { nfree++; if (TYP[v] == 0) { nfA++; } } }')
    L.append('"free unknowns:", nfree, "; free A-coefficients:", nfA;')
    for s in seeds:
        random.seed(s)
        vals = [random.randint(1, p - 1) for _ in range(393)]
        L.append('// point with seed %d' % s)
        L.append('intvec RV = ' + ','.join(map(str, vals)) + ';')
        L.append('ideal PF = maxideal(1); for (v = 1; v <= 393; v++) { if (ELIMAT[v] == 0) { PF[v] = RV[v]; } else { PF[v] = 0; } }')
        L.append('map pf = RP, PF; ideal VAL = pf(IMG);')
        L.append('int okv = 1; for (v = 1; v <= 393; v++) { if (deg(VAL[v]) > 0) { okv = 0; } } "point determined (all coordinates are numbers):", okv;')
        L.append('map ev = RP, VAL; ideal EVAL = ev(EI); "equations vanishing at the point:", size(simplify(EVAL, 2)) == 0;')
        L.append('matrix JP = ev(J); matrix JU = submat(JP, 1..nrows(JP), 1..393);')
        L.append('int r = rank(JU); "seed %d: rank of the Jacobian (w.r.t. the 393 unknowns) mod %d:", r, "; unknowns minus rank:", 393 - r, "; ms:", rtimer-T0;' % (s, p))
        L.append('module K = syz(JU); matrix KM = K; "kernel vectors:", ncols(KM);')
        L.append('matrix KA = submat(KM, 372..393, 1..ncols(KM)); "rank of the projection of the kernel to the 22 A-coefficients:", rank(KA);')
        L.append('kill RV, PF, pf, VAL, okv, ev, EVAL, JP, JU, r, K, KM, KA;')
    L.append('"memory MB:", memory(2) div 1048576, "; ms:", rtimer-T0;')
    L.append('quit;')
    return '\n'.join(L) + '\n'

if __name__ == '__main__':
    cval = int(sys.argv[1]); mode = sys.argv[2]
    seeds = [int(x) for x in sys.argv[3:]] or [11, 12]
    write('n2c%d_%s_modp.sing' % (cval, mode), modp_script(cval, mode, seeds))
    print('ok')
