CANDKEY = r'''
proc candkey(poly f, int m, intvec ORD, intvec TYP)
{
  // best variable of f occurring only in a degree-1 term (constant partial derivative), of order <= m;
  // key = 100*TYP + ORD (lambda first, then highest order); ties: smallest index. Returns (v, key), v = 0 if none.
  intvec res = 0, -1;
  if (f == 0) { return(res); }
  poly j1 = jet(f, 1);
  poly lin = j1 - jet(f, 0);
  if (lin == 0) { return(res); }
  poly nl = f - j1;
  intvec mark = 0:nvars(basering);
  int i;
  if (nl != 0) { ideal vn = variables(nl); for (i = 1; i <= ncols(vn); i++) { mark[rvar(vn[i])] = 1; } }
  int t; int v; int key;
  for (t = 1; t <= size(lin); t++) {
    v = rvar(leadmonom(lin[t]));
    if (v <= 393) {
      if (mark[v] == 0) {
        if (ORD[v] <= m) {
          key = 100*TYP[v] + ORD[v];
          if (key > res[2] || (key == res[2] && v < res[1])) { res = v, key; }
        }
      }
    }
  }
  return(res);
}
proc maxord(poly f, intvec ORD)
{
  // maximal order of an unknown occurring in f (-1 if none)
  int mo = -1; int i;
  ideal vn = variables(f);
  for (i = 1; i <= ncols(vn); i++) { if (vn[i] != 0) { if (rvar(vn[i]) <= 393) { if (ORD[rvar(vn[i])] > mo) { mo = ORD[rvar(vn[i])]; } } } }
  return(mo);
}
'''

def elim_script(cval, mode='stage'):
    """mode 'stage': order-by-order elimination (case_common 3(b)); mode 'global': lambda first by index, no order restriction."""
    L = []
    L.append('// n2, c = %d: constant-pivot elimination, mode %s (generated by gen_n2.py)' % (cval, mode))
    L.append('system("--ticks-per-sec", 1000); int T0 = rtimer;')
    L.append(RING)
    L.append('< "n2_defs.sing";')
    L.append(CANDKEY)
    L.append('link LE = "ssi:r n2c%d_eqs.ssi"; def S = read(LE); close(LE);' % cval)
    L.append('list EQS = S[1]; intvec EQO = S[2]; list EQT = S[3]; int NEQ = size(EQS); kill S;')
    L.append('"equations loaded:", NEQ;')
    L.append('ideal IMG = maxideal(1);')
    L.append('intvec ELIMAT = 0:397;   // stage+1 at which a variable was eliminated (0: free)')
    L.append('intvec ELORD; int nel = 0;   // elimination sequence')
    L.append('ideal E; list ETG; intvec EOG; int ncur = 0;   // current equations (zeros kept as placeholders), tags, w-orders')
    L.append('int m; int u; int v; int i; int nn; int nadd; int bestE; int bestV; int bestKey; int bestSize; poly piv; poly cf; poly expr; intvec ck;')
    L.append('int nst; int nobs; int nrem; int mo; int ntl; int nta;')
    L.append('string sA;')
    if mode == 'stage':
        L.append('int MMAX = 15;')
        L.append('for (m = 0; m <= MMAX; m++) {')
        L.append('  ideal NEW; nn = 0; list NT; intvec NO;')
        L.append('  for (u = 1; u <= NEQ; u++) { if (EQO[u] == m) { nn++; NEW[nn] = EQS[u]; NT[nn] = EQT[u]; } }')
        L.append('  map ph = R, IMG; NEW = ph(NEW); kill ph;')
        L.append('  nadd = 0; for (u = 1; u <= nn; u++) { if (NEW[u] != 0) { ncur++; E[ncur] = NEW[u]; ETG[ncur] = NT[u]; EOG[ncur] = m; nadd++; } }')
        L.append('  ntl = 0; nta = 0; for (v = 1; v <= 393; v++) { if (ORD[v] == m) { if (TYP[v] == 1) { ntl++; } else { nta++; } } }')
        L.append('  "=== stage", m, ": equations of order m:", nn, "; nonzero after substitution of earlier pivots:", nadd, "; unknowns of order m: lambda", ntl, ", A", nta;')
        L.append('  nst = 0; sA = "";')
        L.append('  intvec elcnt = 0:18;   // [1..9]: lambda of order 0..8 eliminated here; [10..16]: A of order 0..6')
        L.append('  while (1) {')
        L.append('    bestE = 0; bestV = 0; bestKey = -1; bestSize = 0;')
        L.append('    for (u = 1; u <= ncur; u++) { if (E[u] != 0) { ck = candkey(E[u], m, ORD, TYP); if (ck[1] > 0) { '
                 'if (ck[2] > bestKey || (ck[2] == bestKey && (size(E[u]) < bestSize || (size(E[u]) == bestSize && ck[1] < bestV)))) { bestKey = ck[2]; bestV = ck[1]; bestE = u; bestSize = size(E[u]); } } } }')
        L.append('    if (bestV == 0) { break; }')
    else:
        L.append('int MMAX = 0; m = 99;')
        L.append('for (u = 1; u <= NEQ; u++) { ncur++; E[ncur] = EQS[u]; ETG[ncur] = EQT[u]; EOG[ncur] = EQO[u]; }')
        L.append('"=== global elimination: all equations at once; priority lambda first by smallest index, then A by smallest index";')
        L.append('nst = 0; sA = ""; intvec elcnt = 0:18;')
        L.append('while (1) {')
        L.append('    bestE = 0; bestV = 0;')
        L.append('    for (u = 1; u <= ncur; u++) { if (E[u] != 0) { ck = candkey(E[u], 99, ORD, TYP); if (ck[1] > 0) { '
                 'if (bestV == 0) { bestV = ck[1]; bestE = u; } else { if ((TYP[ck[1]] > TYP[bestV]) || (TYP[ck[1]] == TYP[bestV] && ck[1] < bestV)) { bestV = ck[1]; bestE = u; } } } } }')
        L.append('    if (bestV == 0) { break; }')
    L.append('    piv = E[bestE]; cf = diff(piv, var(bestV));')
    L.append('    if (deg(cf) != 0) { "ERROR: non-constant pivot"; quit; }')
    L.append('    expr = var(bestV) - piv / cf;')
    L.append('    E[bestE] = 0;')
    L.append('    E = subst(E, var(bestV), expr);')
    L.append('    IMG = subst(IMG, var(bestV), expr);')
    L.append('    nel++; ELORD[nel] = bestV; ELIMAT[bestV] = m + 1; nst++;')
    L.append('    if (TYP[bestV] == 1) { elcnt[ORD[bestV]+1] = elcnt[ORD[bestV]+1] + 1; } else { elcnt[10+ORD[bestV]] = elcnt[10+ORD[bestV]] + 1; sA = sA + string(var(bestV)) + " "; }')
    if mode == 'global':
        L.append('    if (nel mod 50 == 0) { "eliminated", nel, " ms:", rtimer-T0; }')
    L.append('  }')
    L.append('  nrem = 0; nobs = 0; for (u = 1; u <= ncur; u++) { if (E[u] != 0) { nrem++; mo = maxord(E[u], ORD); if (mo < m) { nobs++; } } }')
    L.append('  "   eliminated in this stage:", nst, "; lambda by order 0..8:", intvec(elcnt[1..9]), "; A by order 0..6:", intvec(elcnt[10..16]), "; A eliminated:", sA;')
    L.append('   "   equations remaining:", nrem, "; of these involving only unknowns of order < m (obstructions):", nobs, "; ms:", rtimer-T0, "; memory MB:", memory(2) div 1048576;')
    L.append('  if (nrem > 0 && nrem <= 40) { for (u = 1; u <= ncur; u++) { if (E[u] != 0) { "     remaining eq from", ETG[u], "(order", EOG[u], "), terms", size(E[u]), ", max unknown order", maxord(E[u], ORD), ":", variables(E[u]); } } }')
    if mode == 'stage':
        L.append('  kill NEW, NT, NO, elcnt;')
        L.append('}')
    else:
        L.append('kill elcnt;')
    L.append('"=== end of elimination; eliminated:", nel, "; ms:", rtimer-T0;')
    L.append('int fl = 0; int fa = 0; string sfree = ""; string selA = "";')
    L.append('for (v = 1; v <= 393; v++) { if (ELIMAT[v] == 0) { if (TYP[v] == 1) { fl++; } else { fa++; sfree = sfree + string(var(v)) + " "; } } else { if (TYP[v] == 0) { selA = selA + string(var(v)) + " "; } } }')
    L.append('"free lambda-coefficients:", fl, "; free A-coefficients:", fa, ":", sfree;')
    L.append('"eliminated A-coefficients:", selA;')
    L.append('int nleft = 0; for (u = 1; u <= ncur; u++) { if (E[u] != 0) { nleft++; } } "equations left:", nleft;')
    L.append('ideal LEFT; list LEFTT; int nl2 = 0; for (u = 1; u <= ncur; u++) { if (E[u] != 0) { nl2++; LEFT[nl2] = E[u]; LEFTT[nl2] = ETG[u]; } }')
    L.append('link LS = "ssi:w n2c%d_%s_state.ssi"; write(LS, list(IMG, ELIMAT, ELORD, LEFT, LEFTT)); close(LS);' % (cval, mode))
    L.append('"saved n2c%d_%s_state.ssi; memory MB:", memory(2) div 1048576, "; ms:", rtimer-T0;' % (cval, mode))
    L.append('quit;')
    return '\n'.join(L) + '\n'

