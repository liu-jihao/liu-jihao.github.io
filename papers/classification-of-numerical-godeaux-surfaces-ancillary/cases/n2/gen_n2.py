def mons(n, s):
    """monomials w^a y1^b y2^e y3^f of weight n = a + 2(b+e+f) and sigma-sign s = (-1)^(a+e+f)"""
    out = []
    for a in range(n + 1):
        if (n - a) % 2:
            continue
        m = (n - a) // 2
        for b in range(m + 1):
            for e in range(m - b + 1):
                f = m - b - e
                if (-1) ** (a + e + f) == s:
                    out.append((a, b, e, f))
    return out

def mstr(ex):
    a, b, e, f = ex
    parts = []
    for v, p in (('w', a), ('y1', b), ('y2', e), ('y3', f)):
        if p == 1:
            parts.append(v)
        elif p > 1:
            parts.append('%s^%d' % (v, p))
    return '*'.join(parts) if parts else '1'

