def lampoly(i, j, k):
    terms = []
    for ex in mons(cdeg[i] + cdeg[j] - cdeg[k], dl[i] * dl[j] * dl[k]):
        terms.append('l(%d)*%s' % (lam_index[(i, j, k, ex)], mstr(ex)))
    return ' + '.join(terms) if terms else '0'

