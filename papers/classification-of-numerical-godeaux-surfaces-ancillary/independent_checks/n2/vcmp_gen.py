#!/usr/bin/env python3
"""Compare the c = 1 graph map of my elimination (out_vn2b_c1.txt, free g10 g8 g4 g2 b9 b7 b6 b5) with the case's
(cases/n2/out_n2c1_stage_post.txt, free g3 g4 b2 b4 b7 b9 b10 b12): generates vcmp_c1.sing, which substitutes each
parametrization into the other's 14 relations."""
import re, os
HERE = os.path.dirname(os.path.abspath(__file__))
mine = {}
for line in open(os.path.join(HERE, 'out_vn2b_c1.txt')):
    m = re.match(r'^([gb]\d+) = (.*)$', line.strip())
    if m:
        mine[m.group(1)] = m.group(2)
theirs = {}
for line in list(open('../../cases/n2/out_n2c1_stage_post.txt'))[:40]:
    m = re.match(r'^([gb])\((\d+)\) = (.*)$', line.strip())
    if m:
        expr = re.sub(r'([gb])\((\d+)\)', r'\1\2', m.group(3))
        theirs[m.group(1) + m.group(2)] = expr
assert len(mine) == 14 and len(theirs) == 14, (len(mine), len(theirs))
order = ['g%d' % t for t in range(10, 0, -1)] + ['b%d' % t for t in range(12, 0, -1)]
L = ['// vcmp_c1.sing: compare the two c = 1 graph maps (generated by vcmp_gen.py)',
     'ring R = 0, (%s), dp;' % ','.join(order)]
L.append('ideal MINE = ' + ', '.join('%s - (%s)' % (v, mine[v]) for v in order if v in mine) + ';')
L.append('ideal THEIRS = ' + ', '.join('%s - (%s)' % (v, theirs[v]) for v in order if v in theirs) + ';')
L.append('ideal PM = ' + ', '.join('(%s)' % mine[v] if v in mine else v for v in order) + ';')
L.append('ideal PT = ' + ', '.join('(%s)' % theirs[v] if v in theirs else v for v in order) + ';')
L.append('map FM = R, PM;')
L.append('map FT = R, PT;')
L.append('ideal C1 = FT(MINE);')
L.append('ideal C2 = FM(THEIRS);')
L.append('"my relations not vanishing on the case\'s parametrization: " + string(size(simplify(C1, 2)));')
L.append('"case relations not vanishing on my parametrization: " + string(size(simplify(C2, 2)));')
L.append('"free sets: mine ' + ' '.join(v for v in order if v not in mine) + ' ; case ' + ' '.join(v for v in order if v not in theirs) + '";')
L.append('quit;')
open(os.path.join(HERE, 'vcmp_c1.sing'), 'w').write('\n'.join(L) + '\n')
print('written vcmp_c1.sing')
